<?php

declare(strict_types=1);

/*
 * Writes THIRD-PARTY-LICENSES.md: the third-party code shipped with Patrimeter (Composer dependencies without the
 * development ones, Chart.js copied into assets/vendor/), with its version and license. Each package ships its full
 * license text next to its code (vendor/<package>/, assets/vendor/chart.js/LICENSE.md).
 *
 * Usage: php tools/third-party-licenses.php            writes the file
 *        php tools/third-party-licenses.php --check    exit code 1 if the file is not up to date (test, CI)
 */

$root = dirname(__DIR__);
$lock = json_decode((string) file_get_contents($root . '/composer.lock'), true, flags: JSON_THROW_ON_ERROR);
if (!is_array($lock) || !is_array($lock['packages'] ?? null)) {
    fwrite(STDERR, "composer.lock illisible.\n");
    exit(1);
}

$rows = [];
foreach ($lock['packages'] as $package) {
    if (!is_array($package) || !is_string($package['name'] ?? null)) {
        continue;
    }
    $licenses = array_filter((array) ($package['license'] ?? []), is_string(...));
    $source = is_array($package['source'] ?? null) ? ($package['source']['url'] ?? '') : ($package['homepage'] ?? '');
    $rows[$package['name']] = [
        is_string($package['version'] ?? null) ? $package['version'] : '?',
        $licenses === [] ? '?' : implode(', ', $licenses),
        is_string($source) ? preg_replace('/\.git$/', '', $source) : '',
    ];
}
ksort($rows);

$chart = (string) file_get_contents($root . '/assets/vendor/chart.js/chart.umd.min.js', length: 400);
$chartVersion = preg_match('/Chart\.js v(\d+\.\d+\.\d+)/', $chart, $match) === 1 ? $match[1] : '?';

$lines = [
    '# Third-party licenses',
    '',
    'Third-party code shipped with Patrimeter (MIT license, [LICENSE](LICENSE)): the Composer dependencies installed in',
    'production (`composer install --no-dev`) and Chart.js, copied into `assets/vendor/`. Each one keeps its full license',
    'text next to its code: `vendor/<package>/` and `assets/vendor/chart.js/LICENSE.md`. The development tools (PHPUnit,',
    'PHPStan, Node tools…) are not shipped. Generated by `php tools/third-party-licenses.php` from `composer.lock`.',
    '',
    '| Package | Version | License | Source |',
    '|---|---|---|---|',
    "| Chart.js | $chartVersion | MIT | https://github.com/chartjs/Chart.js |",
];
foreach ($rows as $name => [$version, $license, $source]) {
    $lines[] = "| $name | $version | $license | $source |";
}
$content = implode("\n", $lines) . "\n";

$target = $root . '/THIRD-PARTY-LICENSES.md';
if (in_array('--check', $argv, true)) {
    if (!is_file($target) || file_get_contents($target) !== $content) {
        fwrite(STDERR, "THIRD-PARTY-LICENSES.md n'est pas à jour : php tools/third-party-licenses.php\n");
        exit(1);
    }
    exit(0);
}
file_put_contents($target, $content);
echo 'THIRD-PARTY-LICENSES.md : ' . (count($rows) + 1) . " composants.\n";
